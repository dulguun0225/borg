// Command factory is the crude interface M1 defers the four surfaces with:
// one binary on a terminal, until M7 builds Work, Ops, Factory, and People.
//
// Six subcommands. "run" walks the whole path once — the install, intake, the
// interview, the cut, the spec and implementation stages, the build, the criteria
// in force checked in both directions, the Merge to master gate, the
// fast-forward, the release, the Deploy to production gate, and a straight
// deploy — stopping with the first error, and asking a human for a verdict at
// each row the score or a pin puts one at. "walk <deploy-id>" follows the links
// from an existing deploy record back to its intent, which is the direction M1 is
// demonstrated in — every step a stored field, none reconstructed — and then
// prints every decision the item's gates left in the log.
//
// The other four are duty 8 and duty 9, everything an owner authors and the pins,
// which have no surface of their own until the four of M7 arrive. "area" declares
// a grouping; "author" writes one parameter on the record its scope names;
// "pin" places a pin or withdraws one; "policy" prints every parameter as it is
// in force, where its value came from, and what reads it.
//
// Who may write what: nothing of its own. Every record the run causes to
// exist is written by the package that owns it; this command composes the
// writers and holds no table, and every read goes through the owning
// package's readers.
//
// What defines it: roadmap M1 — "the interface the human decides through is
// whatever is cheapest — the four surfaces come at M7, and a crude interface
// until then is what deferring them costs" —
